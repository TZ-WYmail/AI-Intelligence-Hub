"""Durable local maintenance: SQLite backups and source-based daily briefings."""

import sqlite3
from datetime import timedelta
from pathlib import Path
from urllib.parse import quote, urlsplit, urlunsplit
from zoneinfo import ZoneInfo

from sqlalchemy import func, select
from sqlalchemy.orm import Session

from app.core.config import settings
from app.models import Analysis, Article, Digest, Industry, Metric, Source, now, uid
from app.services.queue import enqueue


def markdown_text(value: str) -> str:
    value = " ".join(value.split())
    return "".join("\\" + char if char in r"\`*_{}[]<>#|" else char for char in value)


def markdown_url(value: str) -> str:
    parts = urlsplit(value)
    if parts.scheme not in {"http", "https"} or not parts.hostname:
        return "#"
    return urlunsplit(
        (parts.scheme, parts.netloc, quote(parts.path, safe="/%:@"), quote(parts.query, safe="=&%:@/?"), "")
    )


def enqueue_maintenance(db: Session) -> None:
    cfg = settings()
    last_backup = db.scalar(
        select(func.max(Metric.recorded_at)).where(Metric.metric_name == "backup_attempt")
    )
    if cfg.backup_enabled and (
        last_backup is None or now() - last_backup >= timedelta(hours=cfg.backup_interval_hours)
    ):
        enqueue(db, "backup", "maintenance:backup")
    local = now().astimezone(ZoneInfo(cfg.app_timezone))
    if cfg.daily_digest_enabled and local.hour >= cfg.daily_digest_hour:
        end = local.replace(hour=0, minute=0, second=0, microsecond=0)
        start = end - timedelta(days=1)
        exists = db.scalar(select(Digest.id).where(Digest.period_start == start, Digest.period_end == end))
        if not exists:
            enqueue(
                db,
                "daily_digest",
                "digest:" + start.isoformat(),
                {"start": start.isoformat(), "end": end.isoformat()},
            )


def backup_database(db: Session) -> dict:
    cfg = settings()
    db.add(Metric(metric_name="backup_attempt", metric_value=1))
    db.commit()
    if not cfg.database_url.startswith("sqlite:///"):
        raise ValueError("BACKUP_REQUIRES_SQLITE")
    directory = Path(cfg.backup_directory)
    directory.mkdir(parents=True, exist_ok=True, mode=0o700)
    destination = directory / ("aih-" + now().strftime("%Y%m%dT%H%M%S") + "-" + uid()[:8] + ".db")
    temporary = destination.with_suffix(".tmp")
    try:
        # Set permissions before writing sensitive database bytes.
        temporary.touch(mode=0o600, exist_ok=False)
        with (
            sqlite3.connect(cfg.database_url.removeprefix("sqlite:///")) as source,
            sqlite3.connect(temporary) as target,
        ):
            source.backup(target)
            if target.execute("PRAGMA integrity_check").fetchone()[0] != "ok":
                raise ValueError("BACKUP_INTEGRITY_FAILED")
        temporary.replace(destination)
        # Only rotate files generated by this service; preserve manually named backups.
        generated = sorted(
            directory.glob("aih-????????T??????-????????.db"),
            key=lambda p: p.stat().st_mtime_ns,
            reverse=True,
        )
        for older in generated[cfg.backup_keep_count :]:
            older.unlink()
        db.add(
            Metric(
                metric_name="backup_success",
                metric_value=destination.stat().st_size,
                labels={"file": destination.name, "integrity": "ok"},
            )
        )
        return {"file": destination.name, "integrity": "ok"}
    finally:
        temporary.unlink(missing_ok=True)


def generate_daily_digest(db: Session, start, end) -> Digest:
    existing = db.scalar(select(Digest).where(Digest.period_start == start, Digest.period_end == end))
    if existing:
        return existing
    cfg = settings()
    from app.models import Event, EventArticle

    query = (
        select(Article, Event.importance_score)
        .join(EventArticle, EventArticle.article_id == Article.id)
        .join(Event, Event.id == EventArticle.event_id)
        .where(Article.published_at >= start, Article.published_at < end)
    )
    total = db.scalar(select(func.count()).select_from(query.subquery()))
    rows = db.execute(
        query.order_by(Event.importance_score.desc(), Article.published_at.desc()).limit(200)
    ).all()
    ids = [article.id for article, _ in rows]
    analyses = {}
    for item in db.scalars(
        select(Analysis)
        .where(
            Analysis.article_id.in_(ids),
            Analysis.status == "completed",
            Analysis.provider == "openai-compatible",
        )
        .order_by(Analysis.created_at.desc())
    ):
        analyses.setdefault(item.article_id, item.analysis_json)
    names = {source.id: source.name for source in db.scalars(select(Source))}
    industries = {item.id: item.name for item in db.scalars(select(Industry))}
    local_start = start.astimezone(ZoneInfo(cfg.app_timezone))
    title = f"每日情报 · {local_start:%Y-%m-%d}"
    lines = [
        "# " + title,
        f"来源发布时间范围：{start.isoformat()} 至 {end.isoformat()}（结束时间不含）",
        f"生成时间：{now().isoformat()}",
        f"共 {total} 条，按规则评分选取前 {len(rows)} 条。",
        "",
        "复用已有 AI 摘要；没有新增模型调用。AI 内容未经独立核验，不等于事实确认。",
        "",
    ]
    if not rows:
        lines.append("本时间范围暂无已处理文章。")
    for article, score in rows:
        ai = analyses.get(article.id)
        summary = ai.get("summary_zh", "") if ai else article.summary
        labels = "、".join(industries.get(identity, identity) for identity in article.industry_ids)
        lines += [
            f"## {markdown_text(article.title)}",
            f"{score} 分 · {markdown_text(labels)} · 未独立核验",
            markdown_text(summary[:1200] or "来源仅提供标题。"),
            f"来源：[{markdown_text(names.get(article.source_id, '原文'))}]({markdown_url(article.original_url)}) · {article.published_at.isoformat()}",
            "AI 摘要" if ai else "来源摘要",
        ]
        if article.publication_time_inferred:
            lines.append("来源未提供可靠发布时间，时间使用发现时间。")
        lines.append("")
    digest = Digest(
        title=title, period_start=start, period_end=end, article_count=total, markdown="\n\n".join(lines)
    )
    db.add(digest)
    db.flush()
    return digest
